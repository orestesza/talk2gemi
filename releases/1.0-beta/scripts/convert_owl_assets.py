#!/usr/bin/env python3
"""Convert approved generated atlas to Flash-resident LVGL RGB565 frames.
Requires Pillow in an isolated image tooling runtime; no firmware dependencies.
16 flat visible colors, binary alpha composited onto the UI background.
RGB565 is deliberate: avoids a full indexed-to-RGB decode allocation at runtime.
"""
from pathlib import Path
from PIL import Image
import json
P=Path(__file__).resolve().parents[1]
source=P/'assets/owl/atlas-alpha-attempt.png'
im=Image.open(source).convert('RGBA');w,h=im.size
BG=(8,15,29);size=80
frames=[]
for i in range(6):
 cell=im.crop(((i%3)*w//3,(i//3)*h//2,(i%3+1)*w//3,(i//3+1)*h//2))
 mask=cell.getchannel('A').point(lambda a:255 if a>=128 else 0)
 box=mask.getbbox()
 if not box:raise RuntimeError('Empty sprite')
 # Preserve equal cell scale instead of independently stretching the poses.
 cell.putalpha(mask)
 canvas=Image.new('RGBA',cell.size,BG+(255,));canvas.alpha_composite(cell)
 frames.append(canvas.convert('RGB').resize((size,size),Image.Resampling.NEAREST))
# Common palette: background plus 15 foreground colors across the entire atlas.
strip=Image.new('RGB',(size*6,size),BG)
for i,f in enumerate(frames):strip.paste(f,(i*size,0))
q=strip.quantize(colors=16,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE).convert('RGB')
# Keep all background pixels exactly equal to screen fill (no rectangular seams).
for i,f in enumerate(frames):
 out=q.crop((i*size,0,(i+1)*size,size))
 for y in range(size):
  for x in range(size):
   if f.getpixel((x,y))==BG:out.putpixel((x,y),BG)
 frames[i]=out
# Re-quantize with fixed 15 foreground colors + exact background to enforce <=16.
palette=q.quantize(colors=15).getpalette()[:45]+list(BG)
pal=Image.new('P',(1,1));pal.putpalette(palette+[0]*(768-len(palette)))
frames=[f.quantize(palette=pal,dither=Image.Dither.NONE).convert('RGB') for f in frames]
lines=['/* Generated by scripts/convert_owl_assets.py; do not hand edit. */','#include "owl_assets.h"']
for i,f in enumerate(frames):
 f.save(P/f'assets/owl/frame-{i}.png')
 display_frame=f.resize((160,160),Image.Resampling.NEAREST)
 vals=[]
 for r,g,b in display_frame.getdata():
  v=((r>>3)<<11)|((g>>2)<<5)|(b>>3);vals.extend([v&255,v>>8])
 lines.append(f'static const uint8_t pixels_{i}[] __attribute__((aligned(4))) = {{')
 lines.extend(','.join(f'0x{n:02x}' for n in vals[j:j+32])+',' for j in range(0,len(vals),32));lines.append('};')
lines.append('const lv_image_dsc_t owl_frames[6] = {')
for i in range(6):lines.append('{.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565,.w=160,.h=160,.stride=320},.data_size=51200,.data=pixels_%d},'%i)
lines.append('};')
(P/'firmware/main/owl_assets.c').write_text('\n'.join(lines)+'\n')
(P/'firmware/main/owl_assets.h').write_text('#pragma once\n#include "lvgl.h"\nextern const lv_image_dsc_t owl_frames[6];\n')
preview=Image.new('RGB',(480,320),BG)
for i,f in enumerate(frames):preview.paste(f.resize((160,160),Image.Resampling.NEAREST),((i%3)*160,(i//3)*160))
preview.save(P/'assets/owl/frames-preview.png')
(P/'assets/owl/conversion.json').write_text(json.dumps(dict(size=size,frames=6,colors=len(set(c for f in frames for c in f.getdata())),storage='RGB565 const Flash, no frame decode buffer',source_size=80,display_size=160,frame_bytes=51200),indent=2))
print('Converted 6 frames, 80x80, Flash bytes',6*51200)
